#!/usr/bin/env python3
"""Generate docs/SCRIPT_TASKS.md from fid/task_kinds.csv (Unicorn-derived task descriptors) and fid/script_command_names.csv."""
import collections
import csv
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CAT = (('Camera', 'camera'), ('MapCtl', 'actor motion/face'), ('StateLogic_UpdateDataChi', 'actor motion/face'), ('ScreenFade', 'screen fade'),
       ('Bg_', 'background layers'), ('GameSnd', 'sound'), ('SaveSlot', 'heroine record / stats'), ('GameFlags', 'flags'),
       ('Stats', 'stats'), ('Scene_', 'scene change'), ('Overlay', 'overlay scenes'), ('Ov02', 'skinship (overlay 2)'),
       ('Ov41', 'overnight (overlay 41)'), ('Calendar', 'calendar'), ('EventLogic', 'event records'), ('EventAssets', 'event assets'),
       ('TextVar', 'text variables'), ('Msg', 'message box'), ('Schedule', 'schedule'), ('TaskList_AllocTask', 'task only'),
       ('Counter', 'counters'), ('Slot', 'slot workflow'), ('Deadline', 'deadlines'), ('GameClock', 'clock'))


def category(effect):
    for pre, cat in CAT:
        if pre in effect:
            return cat
    return 'other'


def main():
    names = {r['cmd']: r['name'] for r in csv.DictReader(open(os.path.join(ROOT, 'fid/script_command_names.csv')))}
    usage = {r['cmd']: int(r['uses']) for r in csv.DictReader(open(os.path.join(ROOT, 'fid/script_command_names.csv')))}
    rows = list(csv.DictReader(open(os.path.join(ROOT, 'fid/task_kinds.csv'))))
    by = collections.defaultdict(list)
    for r in rows:
        by[category(r['effects'])].append(r)
    out = ['# Script task kinds (generated by tools/task_ref.py)', '',
           'Every command that has a lasting effect builds a *task descriptor* `{kind, count, (type, value)...}` and runs it through `TaskList_TickTaskMain` (0x206ce34, 11.5 KB switch over ~195 kinds): '
           'the function applies the kind\'s native effect and, for query kinds, returns a value (used by script `acc`). '
           'The script `yield` (cmd 0x1) waits until no task of the current kind remains (`TaskList_IsNoTaskOfCurrentKind`). '
           'A task is freed by a completion predicate set with `Input_SetSlotParams(slot, predicate)`: ', '',
           '- `TaskList_FreeAfterCountdown`: counts the task\'s `ticks` down (cmd 0x44 wait, bg commands 0xf5-0xf8);',
           '- `TaskList_FreeWhenXformFlagClear/Set`: waits for the camera/transform flag (camera presets with transition, camera mode 2);',
           '- `TaskList_FreeAfterFadesIdleThreeTicks`: both screen fades idle for 3 ticks (cmd 0xd, 0xe);',
           '- `TaskList_TickSubstateWithSound`, `TickFadeSequence`, `FreeWhenMsgBoxClosed`: sound/fade/message waits;',
           '- `TaskList_FreeWhenExtFn<addr>...`: overlay-provided predicates (skinship overlay 2, overnight overlay 41, mini-game overlays);',
           '- no predicate: the effect is instantaneous (motion/face/state commands) or the handler itself waits.', '',
           'Effect strings are the native calls recorded while running the real handler with tagged arguments (`a0..` = script args, `CHAR` = character ref).', '']
    for cat in sorted(by, key=lambda c: -len(by[c])):
        out += ['## %s' % cat, '', '| kind | command(s) | effect |', '|---|---|---|']
        for r in sorted(by[cat], key=lambda r: int(r['kind'], 16)):
            cmds = ', '.join('%s %s' % (c, names.get(c, '')) for c in r['commands'].split())
            out.append('| %s | %s | %s |' % (r['kind'], cmds, r['effects'].replace('|', '/')[:200]))
        out.append('')
    open(os.path.join(ROOT, 'docs/SCRIPT_TASKS.md'), 'w').write('\n'.join(out))
    print(len(rows), 'kinds,', len(by), 'categories')


if __name__ == '__main__':
    main()
