"""Summarise calendar_probe.py output (native calendar module run over every code/year/day) into docs/CALENDAR.md.
usage: calendar_doc.py probe1.json [probe2.json ...]"""
import json, sys
from collections import Counter

codes = {}
for p in sys.argv[1:]:
    codes.update(json.load(open(p))['codes'])
fixed, var, never = [], [], []
for c in sorted(codes, key=int):
    sets = {y: tuple(map(tuple, v)) for y, v in codes[c].items()}
    mx = max(len(v) for v in sets.values())
    if mx == 0:
        never.append(c)
    elif len(set(sets.values())) == 1:
        fixed.append((c, next(iter(sets.values()))))
    else:
        var.append((c, sets))
out = ['# Calendar event codes', '',
       'Generated by `tools/calendar_doc.py` from `tools/calendar_probe.py`, which runs the native calendar module',
       '(`Calendar_IsEventActive`, 0x20a8700-0x20ac000) for every code, game year 0..27 (two-digit year; a 28-year',
       'cycle covers every weekday alignment) and every month/day.', '',
       f'{len(codes)} codes probed: {len(fixed)} fixed-date, {len(var)} year-dependent, {len(never)} never active.', '',
       '## Fixed-date codes (same days every year)', '', '| code | month/day |', '|---|---|']
for c, s in fixed:
    out.append(f'| {c} | ' + ', '.join(f'{m}/{d}' for m, d in s) + ' |')
out += ['', '## Year-dependent codes (weekday / moving-holiday rules)', '',
        '| code | days per year (min-max) | distinct yearly patterns |', '|---|---|---|']
for c, sets in var:
    n = [len(v) for v in sets.values()]
    out.append(f'| {c} | {min(n)}-{max(n)} | {len(set(sets.values()))} |')
out += ['', '## Never active', '', ', '.join(never), '',
        'Year-dependent patterns repeat with the 28-year cycle; the per-year day lists are in the probe JSON (local, regenerate with `calendar_probe.py`).']
open('docs/CALENDAR.md', 'w').write('\n'.join(out) + '\n')
print(len(fixed), len(var), len(never))
