    #[test]
    fn queries_rand_and_unknown_commands() {
        let mut a = Asm::new();
        let mut code = cmd(0xa7, &[10]);
        code.extend(cmd(0x1fb, &[1]));
        code.extend(cmd(0x1ab, &[])); // an unclassified command
        code.extend(ins(0x13, &[]));
        let mut h = host_for(vec![a.build(vec![code])], &[(0xa000_6600, 0, 0)]);
        let tr = h.run_event(0xa000_6600, &mut DefaultPolicy).unwrap();
        let e = effects(&tr);
        match e[0] {
            Effect::Query { reply, modelled, name, .. } => {
                assert!(*reply < 10 && *modelled);
                assert_eq!(name, "rand");
            }
            x => panic!("{x:?}"),
        }
        assert!(matches!(e[1], Effect::Query { reply: 0, modelled: true, .. })); // Manaka = slot 0
        assert!(matches!(e[2], Effect::Command { id: 0x1ab, .. }));
        // same seed, same random
        let mut h2 = host_for(vec![Asm::new().build(vec![{ let mut c = cmd(0xa7, &[10]); c.extend(ins(0x13, &[])); c }])], &[(9, 0, 0)]);
        let t2 = h2.run_event(9, &mut DefaultPolicy).unwrap();
        assert_eq!(effects(&t2)[0], e[0]);
        // policy override
        let mut sc = Scripted::new(vec![]);
        sc.queries.insert(0xa7, 4);
        let mut h3 = host_for(vec![Asm::new().build(vec![{ let mut c = cmd(0xa7, &[10]); c.extend(ins(0x13, &[])); c }])], &[(9, 0, 0)]);
        assert!(matches!(effects(&h3.run_event(9, &mut sc).unwrap())[0], Effect::Query { reply: 4, .. }));
    }

    #[test]
    fn calls_into_another_script_and_returns() {
        let mut b = Asm::new();
        let sb = b.say("B", "from the callee", None);
        let mut cb = sb;
        cb.extend(ins(0x13, &[]));
        let mut a = Asm::new();
        let s1 = a.say("A", "before", None);
        let s2 = a.say("A", "after", None);
        let mut ca = s1;
        ca.extend(ins(0x16, &[0, 0x200])); // call event 0x200 (script 1)
        ca.extend(s2);
        ca.extend(ins(0x13, &[]));
        let mut h = host_for(vec![a.build(vec![ca]), b.build(vec![cb])], &[(0x100, 0, 0), (0x200, 1, 0)]);
        let tr = h.run_event(0x100, &mut DefaultPolicy).unwrap();
        let seq: Vec<String> = effects(&tr).into_iter().map(|e| match e { Effect::Dialogue { text, .. } => text.clone(), Effect::CallEvent { event_id } => format!("call {event_id:#x}"), _ => String::new() }).filter(|s| !s.is_empty()).collect();
        assert_eq!(seq, vec!["before", "call 0x200", "from the callee", "after"]);
    }

